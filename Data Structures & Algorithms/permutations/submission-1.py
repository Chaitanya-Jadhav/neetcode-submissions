class Solution:
    def permute(self, nums: List[int]) -> List[List[int]]:
        # BASE CASE: 
        # If the input list is empty, there is only one permutation: an empty list.
        # We return a list containing an empty list because the return type must be List[List[int]].
        if len(nums) == 0:
            return [[]]
        
        # RECURSIVE STEP: 
        # Find all permutations of the sub-array that excludes the first element (nums[0]).
        # For example, if nums is [1, 2, 3], we recursively find permutations of [2, 3].
        perms = self.permute(nums[1:])
        
        # This list will store the final permutations for the current level of recursion.
        res = []

        # Iterate through every permutation generated by the recursive call.
        for p in perms:
            # We need to insert the excluded first element (nums[0]) into every possible 
            # position of the current permutation 'p'.
            # The number of possible positions is len(p) + 1 (beginning, middle(s), and end).
            for i in range(len(p) + 1):
                # Make a copy of the current permutation so we don't modify the original list 'p'
                # while we are iterating and modifying it for different positions.
                p_copy = p.copy()
                
                # Insert the first element of the current 'nums' into the copied permutation at index 'i'.
                p_copy.insert(i, nums[0])
                
                # Append the newly created permutation to our results list.
                res.append(p_copy)

        # Return the collected permutations back up the recursion tree.
        return res